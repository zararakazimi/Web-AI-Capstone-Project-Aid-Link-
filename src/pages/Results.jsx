import { Link, useLocation } from "react-router-dom";
import organizationsData from "../data/organizations";
import OrganizationCard from "../components/OrganizationCard";

function Results() {
  const { state } = useLocation();

  if (!state?.aiResponse) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-100">
        <div className="text-center bg-white p-10 rounded-3xl shadow-xl">
          <h1 className="text-3xl font-bold text-gray-800 mb-4">
            No Analysis Available
          </h1>

          <p className="text-gray-600 mb-6">
            Please submit your situation first so AidLink AI can analyze it.
          </p>

          <Link
            to="/request-help"
            className="bg-blue-600 hover:bg-blue-700 text-white px-6 py-3 rounded-xl font-semibold transition"
          >
            Request Help
          </Link>
        </div>
      </div>
    );
  }

  const response = state.aiResponse;

  // Extract sections from AI response
  const needs =
    response.match(
      /## Needs Assessment([\s\S]*?)## Recommended Categories/i
    )?.[1]?.trim() || "";

  const categories =
    response.match(
      /## Recommended Categories([\s\S]*?)## Action Plan/i
    )?.[1]?.trim() || "";

  const action =
    response.match(
      /## Action Plan([\s\S]*)/i
    )?.[1]?.trim() || "";

  // Convert categories into an array
  const detectedCategories = categories
    .split("\n")
    .map((item) =>
      item
        .replace("-", "")
        .replace("*", "")
        .trim()
        .toLowerCase()
    )
    .filter(Boolean);

  // Match organizations from our database
  const recommendedOrganizations = organizationsData.filter((organization) =>
    organization.categories.some((category) =>
      detectedCategories.includes(category.toLowerCase())
    )
  );

  return (
    <div className="min-h-screen bg-slate-100 py-10 px-5">
      <div className="max-w-7xl mx-auto">
                {/* Hero Section */}
        <div className="bg-gradient-to-r from-blue-700 via-cyan-600 to-teal-600 rounded-3xl shadow-2xl text-white p-10 mb-10">
          <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-6">
            <div>
              <h1 className="text-4xl md:text-5xl font-bold mb-4">
                🤝 Your Personalized Support Plan
              </h1>

              <p className="text-lg text-blue-100 leading-8 max-w-3xl">
                AidLink AI carefully analyzed your situation and identified the
                support services that best match your needs. Review the
                recommendations below and explore organizations that may be able
                to assist you.
              </p>
            </div>

            <div className="bg-white/20 backdrop-blur-sm rounded-2xl px-8 py-6 text-center">
              <div className="text-5xl mb-2">🤖</div>

              <h3 className="font-bold text-xl">
                AI Analysis Complete
              </h3>

              <p className="text-blue-100 mt-2">
                Personalized recommendations are ready.
              </p>
            </div>
          </div>
        </div>

        {/* Needs Assessment */}
        <div className="bg-white rounded-3xl shadow-xl p-8 border-l-8 border-blue-600 mb-10">

          <div className="flex items-center mb-6">
            <div className="w-14 h-14 rounded-full bg-blue-100 flex items-center justify-center text-3xl">
              📋
            </div>

            <div className="ml-4">
              <h2 className="text-3xl font-bold text-blue-700">
                Understanding Your Situation
              </h2>

              <p className="text-gray-500">
                Summary generated by AidLink AI
              </p>
            </div>
          </div>

          <div className="bg-blue-50 rounded-2xl p-6">
            <p className="text-gray-700 text-lg leading-9 whitespace-pre-wrap">
              {needs}
            </p>
          </div>

        </div>

                {/* Recommended Organizations */}
        <div className="mb-10">

          <div className="flex items-center mb-6">
            <div className="w-14 h-14 rounded-full bg-green-100 flex items-center justify-center text-3xl">
              🌍
            </div>

            <div className="ml-4">
              <h2 className="text-3xl font-bold text-green-700">
                Recommended Organizations
              </h2>

              <p className="text-gray-500">
                Organizations that match your needs
              </p>
            </div>
          </div>

          {recommendedOrganizations.length > 0 ? (

            <div className="grid md:grid-cols-2 xl:grid-cols-3 gap-6">
              {recommendedOrganizations.map((organization) => (
                <OrganizationCard
                  key={organization.id}
                  organization={organization}
                />
              ))}
            </div>

          ) : (

            <div className="bg-yellow-50 border border-yellow-300 rounded-3xl p-10 text-center">

              <div className="text-6xl mb-4">
                🔍
              </div>

              <h3 className="text-2xl font-bold text-yellow-700 mb-4">
                No Matching Organizations Found
              </h3>

              <p className="text-gray-600 max-w-2xl mx-auto leading-8">
                AidLink could not find organizations matching the support
                categories identified by the AI. You can browse our complete
                organization directory to explore all available services.
              </p>

              <Link
                to="/organizations"
                className="inline-block mt-8 bg-green-600 hover:bg-green-700 text-white px-8 py-3 rounded-xl font-semibold transition"
              >
                Browse All Organizations
              </Link>

            </div>

          )}

        </div>

        {/* Action Plan */}
        <div className="mb-10">

          <div className="flex items-center mb-6">
            <div className="w-14 h-14 rounded-full bg-orange-100 flex items-center justify-center text-3xl">
              ✅
            </div>

            <div className="ml-4">
              <h2 className="text-3xl font-bold text-orange-600">
                Your Action Plan
              </h2>

              <p className="text-gray-500">
                Recommended next steps
              </p>
            </div>
          </div>

          <div className="grid gap-5">

            {action
              .split("\n")
              .filter((step) => step.trim() !== "")
              .map((step, index) => (

                <div
                  key={index}
                  className="bg-white rounded-2xl shadow-lg p-6 border-l-8 border-orange-500 hover:shadow-xl transition"
                >

                  <div className="flex items-start">

                    <div className="w-12 h-12 rounded-full bg-orange-500 text-white flex items-center justify-center font-bold text-lg mr-5 flex-shrink-0">
                      {index + 1}
                    </div>

                    <div>

                      <h3 className="text-xl font-bold text-orange-600 mb-2">
                        Step {index + 1}
                      </h3>

                      <p className="text-gray-700 leading-8">
                        {step.replace(/^\d+\./, "").trim()}
                      </p>

                    </div>

                  </div>

                </div>

              ))}

          </div>

        </div>

                {/* AidLink Advice */}
        <div className="bg-blue-50 rounded-3xl shadow-lg p-8 mb-10 border border-blue-100">

          <div className="flex items-center mb-5">
            <div className="w-14 h-14 rounded-full bg-blue-600 text-white flex items-center justify-center text-3xl">
              💡
            </div>

            <div className="ml-4">
              <h2 className="text-3xl font-bold text-blue-700">
                AidLink Advice
              </h2>

              <p className="text-gray-500">
                Important information before requesting support
              </p>
            </div>
          </div>

          <p className="text-gray-700 leading-8 text-lg">
            These recommendations were generated by AidLink AI based on the
            information you provided. They are designed to help you identify
            organizations that may be able to assist you. Before applying,
            always visit the organization's official website to confirm its
            services, eligibility requirements, and contact information.
          </p>

        </div>

        {/* Action Buttons */}
        <div className="flex flex-col md:flex-row justify-center gap-5 mb-10">

          <Link
            to="/request-help"
            className="bg-blue-600 hover:bg-blue-700 text-white text-center px-8 py-4 rounded-xl font-bold transition duration-300 shadow-lg"
          >
            🔄 Analyze Another Situation
          </Link>

          <Link
            to="/organizations"
            className="bg-green-600 hover:bg-green-700 text-white text-center px-8 py-4 rounded-xl font-bold transition duration-300 shadow-lg"
          >
            🌍 Browse Organizations
          </Link>

        </div>

      </div>
    </div>
  );
}

export default Results;
